"""相关性筛除：判断"检索到的材料到底能不能回答这个问题"。

这是拒答能力的第一道关卡，也是 RAG 系统最容易被忽略的一环。

为什么必须显式做这件事：向量检索永远会返回结果。余弦相似度的取值范围里
没有"无关"这个取值，只要索引非空，top_k 就一定会被填满。于是一个关于
"公司上一财年净利润增长率"的问题，会在一个只讲软件架构的语料里检索出
五条得分为正的材料——然后模型拿着这五条材料，被要求"必须带引用作答"，
它就只能硬凑。加一道相关性筛除，比在提示词里写十遍"不要编造"更有用。

判据为什么用词法重合度而不是向量分数：
  1. 它必须在无模型、无网络的 CI 上可用，且结果确定；
  2. 它必须能被人工手算复核——对一个"要不要拒答"的决定，可复核性比精度更重要；
  3. 向量分数在不同嵌入模型之间不可比（bge-m3 的 0.5 与别的模型的 0.5 不是一回事），
     而词法覆盖率在任何环境下含义相同。

代价说清楚：问法与语料用词差异很大时（同义改写、跨语言提问），词法覆盖率会偏低，
真实相关的问题可能被误判为不相关。所以阈值可配置。默认值的依据是实测分布
（9 块语料、查询侧分词）：真相关问题的最佳覆盖度在 0.375 以上，
无关问题在 0.167 以下——默认 0.3 落在间隔内，两类各留约 1.3 倍余量。
"""

from __future__ import annotations

from collections.abc import Sequence

from ...contracts.text import query_overlap_ratio


def coverage(question: str, text: str) -> float:
    """问题里的内容词有多大比例能在给定文本里找到。区间 [0, 1]。

    必须用查询侧分词（丢单字）。这里曾踩过坑：早期直接复用 overlap_ratio，
    两侧都是文档侧分词，单字把无关问题的覆盖率抬到门槛之上——
    实测"量子纠缠的退相干时间"在一个软件架构语料上拿到 0.360，
    而当时的默认门槛是 0.300，这道筛除形同虚设。换成查询侧分词后
    同一问题降到 0.167，两类问题的区间从"重叠"变成"干净分开"（见
    query_overlap_ratio 的文档字符串）。
    """
    return query_overlap_ratio(question, text)


def best_coverage(question: str, evidence: Sequence) -> float:
    """所有材料中最佳的那一条覆盖度。

    取最大值而不是看排名第一的那条：检索排序可能因为某个共同词
    把一条无关材料顶到首位，而"库里是否存在能回答这个问题的材料"
    问的是集合层面的属性，不是排序层面的属性。
    """
    best = 0.0
    for item in evidence:
        chunk = getattr(item, "chunk", item)
        best = max(best, coverage(question, getattr(chunk, "text", "") or ""))
    return round(best, 6)


__all__ = ["coverage", "best_coverage"]
